#!/usr/bin/env node
/**
 * Auto-generates docs/ICONS.md from the two Icon registries so the semantic
 * icon naming stays a single source of truth. Re-run after changing either
 * registry:  node scripts/gen-icon-docs.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const WEB = path.join(ROOT, "frontend/src/components/Icon.jsx");
const MOB = path.join(ROOT, "mobile/src/components/Icon.tsx");

function parseWeb(src) {
  // capture the ICONS = { ... } block, then `name: Component,`
  const block = src.slice(src.indexOf("export const ICONS = {"));
  const map = {};
  const re = /^\s*["']?([A-Za-z-]+)["']?:\s*([A-Za-z0-9]+),/gm;
  let m;
  while ((m = re.exec(block))) {
    if (m[1] === "default") continue;
    map[m[1]] = m[2];
  }
  return map;
}

function parseMobile(src) {
  const block = src.slice(src.indexOf("export const ICONS: Record"));
  const map = {};
  const re = /^\s*["']?([A-Za-z-]+)["']?:\s*\{\s*fam:\s*"(\w+)"(?:,\s*glyph:\s*"([^"]+)")?/gm;
  let m;
  while ((m = re.exec(block))) {
    const [, name, fam, glyph] = m;
    map[name] = fam === "ion" ? `Ionicons \`${glyph}\`` : fam === "mci" ? `MCI \`${glyph}\`` : "Burgee (custom SVG)";
  }
  return map;
}

const web = parseWeb(fs.readFileSync(WEB, "utf8"));
const mob = parseMobile(fs.readFileSync(MOB, "utf8"));
const names = Array.from(new Set([...Object.keys(web), ...Object.keys(mob)])).sort();

const lines = [];
lines.push("# Icon Reference (auto-generated)");
lines.push("");
lines.push("> Generated by `scripts/gen-icon-docs.js` from the two `<Icon>` registries.");
lines.push("> DO NOT edit by hand — re-run the script after changing a registry.");
lines.push("");
lines.push(`**${names.length} semantic icons.** Usage: \`<Icon name=\"crew\" tone=\"brand\" size={24} />\``);
lines.push("");
lines.push("Tones: `default` · `muted` · `accent` · `brand` · `onAccent` · `disabled`" +
  " (web adds `current` = inherit parent color).");
lines.push("");
lines.push("| `name` | Web (lucide) | Mobile (@expo/vector-icons) |");
lines.push("|---|---|---|");
for (const n of names) {
  const w = web[n] ? `\`${web[n]}\`` : (n === "org" || n === "partner" ? "`Burgee`" : "—");
  const mo = mob[n] || "—";
  lines.push(`| \`${n}\` | ${w} | ${mo} |`);
}
lines.push("");

const out = path.join(ROOT, "docs/ICONS.md");
const content = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== content) {
    console.error(
      "\u2716 docs/ICONS.md is stale. An <Icon> registry changed but ICONS.md was not regenerated.\n" +
        "  Run:  node scripts/gen-icon-docs.js   (then commit docs/ICONS.md)",
    );
    process.exit(1);
  }
  console.log(`\u2713 docs/ICONS.md is up to date (${names.length} icons)`);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, content);
  console.log(`Wrote ${out} (${names.length} icons)`);
}
